import { mkdir, readFile, stat, writeFile } from "node:fs/promises";
import { join } from "node:path";
import { fileURLToPath } from "node:url";
import { expect, test } from "@playwright/test";
import { fauxAssistantMessage } from "@earendil-works/pi-ai/compat";
import { createAssistantFixture } from "../../workbench-server/test/assistant-fixture.ts";

test("directory name is previewed and deleting from the browser removes project sessions and managed files, retaining the source and USER.md", async ({ page }) => {
	let sourcePath = "";
	const fixture = await createAssistantFixture(fileURLToPath(new URL("../dist", import.meta.url)), { pickDirectory: async () => sourcePath });
	const errors: string[] = [];
	page.on("pageerror", (error) => errors.push(error.message));
	try {
		sourcePath = join(fixture.root, "项目删除 中文 空格");
		await mkdir(sourcePath);
		await writeFile(join(sourcePath, "保留.txt"), "保留源文件");
		const user = await fixture.application.services.memory.propose({}, { kind: "user", proposedText: "用户偏好简短中文。", reason: "确认偏好" });
		await fixture.application.services.memory.accept(user.id);
		const before = await readFile(fixture.application.paths.userMemory, "utf8");
		await page.goto(fixture.address.launchUrl);
		await page.goto(`${fixture.address.origin}/projects`);
		await page.getByRole("button", { name: "打开文件夹为项目", exact: true }).click();
		await expect(page.getByLabel("项目名称", { exact: true })).toHaveValue("项目删除 中文 空格");
		await page.getByRole("button", { name: "创建项目", exact: true }).click();
		await expect(page.locator(".project-title h1")).toHaveText("项目删除 中文 空格");
		const project = (await fixture.application.services.projects.list())[0];
		await page.getByLabel("启动助手预设", { exact: true }).selectOption((await fixture.application.services.profiles.getBySlug("standard")).id);
		await page.getByRole("button", { name: "启动助手", exact: true }).click();
		fixture.faux.setResponses([fauxAssistantMessage("待删除会话的实际 Pi 历史。")]);
		await page.getByRole("textbox", { name: "消息输入" }).fill("创建删除验收的会话历史");
		await page.getByRole("button", { name: "发送消息" }).click();
		await expect(page.locator(".toolbar-state")).toHaveText("就绪");
		const session = (await fixture.application.services.sessions.list(project.id))[0];
		await page.locator(".project-header").getByRole("button", { name: "删除项目 项目删除 中文 空格", exact: true }).click();
		const dialog = page.getByRole("dialog", { name: "删除项目", exact: true });
		await expect(dialog).toContainText("会话 1");
		await expect(dialog).toContainText("本机源目录保留");
		await dialog.getByRole("button", { name: "取消", exact: true }).click();
		expect(await stat(project.memoryFilePath)).toBeDefined();
		await page.goto(`${fixture.address.origin}/projects`);
		await page.locator(".project-card").getByRole("button", { name: "删除项目 项目删除 中文 空格", exact: true }).click();
		await dialog.getByRole("button", { name: "删除项目及工作台数据", exact: true }).click();
		await expect(dialog).toHaveCount(0);
		await expect(page.locator(".project-card")).toHaveCount(0);
		await expect(stat(project.workspacePath)).rejects.toMatchObject({ code: "ENOENT" });
		await expect(stat(session.runtimeRef)).rejects.toMatchObject({ code: "ENOENT" });
		expect(await readFile(join(sourcePath, "保留.txt"), "utf8")).toBe("保留源文件");
		expect(await readFile(fixture.application.paths.userMemory, "utf8")).toBe(before);
		await page.goto(`${fixture.address.origin}/memory`);
		await expect(page.getByRole("heading", { name: "四层记忆", exact: true })).toHaveCount(0);
		await expect(page.locator(".memory-library")).toContainText("USER.md");
		await fixture.restart();
		await page.goto(fixture.address.launchUrl);
		await page.goto(`${fixture.address.origin}/projects`);
		await expect(page.locator(".project-card")).toHaveCount(0);
		expect(await fixture.application.services.sessions.list()).toEqual([]);
		expect(errors).toEqual([]);
	} finally { await fixture.close(); }
});
