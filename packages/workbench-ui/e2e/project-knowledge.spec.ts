import { mkdir, writeFile } from "node:fs/promises";
import { createServer } from "node:http";
import { join } from "node:path";
import { fileURLToPath } from "node:url";
import { fauxAssistantMessage } from "@earendil-works/pi-ai/compat";
import { expect, test } from "@playwright/test";
import { createAssistantFixture } from "../../workbench-server/test/assistant-fixture.ts";

test("a selected folder becomes a project with a searchable, restart-safe knowledge index", async ({ page }) => {
	let sourcePath = "";
	const fixture = await createAssistantFixture(fileURLToPath(new URL("../dist", import.meta.url)), { pickDirectory: async () => sourcePath });
	const embedding = createServer(async (request, response) => {
		let body = "";
		for await (const chunk of request) body += chunk.toString();
		const input = (JSON.parse(body) as { input: string[] }).input;
		response.setHeader("content-type", "application/json");
		response.end(JSON.stringify({ data: input.map((text, index) => ({ index, embedding: /vision|视觉/iu.test(text) ? [1, 0] : [0, 1] })) }));
	});
	await new Promise<void>((resolve) => embedding.listen(0, "127.0.0.1", resolve));
	try {
		const address = embedding.address();
		if (!address || typeof address === "string") throw new Error("No embedding test port");
		sourcePath = join(fixture.root, "视觉学习");
		await mkdir(sourcePath);
		await writeFile(fixture.embeddingEnvFile, `EMBED_API_KEY=browser-test-secret\nEMBED_BASE_URL=http://127.0.0.1:${address.port}/v1\nEMBED_MODEL_NAME=browser-test\nEMBED_TOKENIZER=cl100k_base\nEMBED_TOKENIZER_MODEL=browser-test\n`);
		await writeFile(join(sourcePath, "README.md"), "视觉 vision baseline and dataset notes.");
		await page.goto(fixture.address.launchUrl);
		await page.getByRole("link", { name: "项目", exact: true }).first().click();
		await page.getByRole("button", { name: "打开文件夹为项目" }).click();
		await page.getByRole("button", { name: "浏览文件夹…" }).click();
		await page.getByRole("button", { name: "创建项目" }).click();
		await expect(page.locator(".project-title")).toContainText("视觉学习");
		await page.locator(".project-tabs").getByRole("link", { name: "知识库" }).click();
		await expect(page.locator("html")).toHaveAttribute("data-theme", "light");
		const lightBackground = await page.evaluate<string>("getComputedStyle(document.body).backgroundColor");
		await page.getByRole("button", { name: "切换主题" }).click();
		await expect(page.locator("html")).toHaveAttribute("data-theme", "dark");
		await expect.poll(() => page.evaluate<string>("getComputedStyle(document.body).backgroundColor")).not.toBe(lightBackground);
		await page.reload();
		await expect(page.locator("html")).toHaveAttribute("data-theme", "dark");
		await page.getByRole("button", { name: "切换主题" }).click();
		await expect(page.locator("html")).toHaveAttribute("data-theme", "light");
		await expect.poll(() => page.evaluate<string>("getComputedStyle(document.body).backgroundColor")).toBe(lightBackground);
		await expect(page.locator(".project-source-path")).toContainText(sourcePath);
		await expect(page.getByText("文件：0 · 片段：0")).toBeVisible();
		await page.getByRole("button", { name: "建立／更新索引" }).click();
		await expect(page.getByText("文件：1 · 片段：1")).toBeVisible();
		await page.getByLabel("检索项目资料").fill("vision");
		await page.getByRole("button", { name: "检索", exact: true }).click();
		await expect(page.getByRole("heading", { name: "README.md · 片段 1" })).toBeVisible();
		await expect(page.locator(".knowledge-search-trace")).toContainText("实际查询");
		await expect(page.locator(".knowledge-search-trace")).toContainText("自动策略使用原查询");
		await page.getByText("分块与检索参数", { exact: true }).click();
		await page.getByLabel("片段 Token 上限").fill("256");
		await page.getByLabel("短片段合并阈值").fill("40");
		await page.getByLabel("上下文 Token 预算").fill("768");
		await page.getByLabel("多查询扩展（MQE）").selectOption("always");
		await page.getByRole("button", { name: "保存参数" }).click();
		await expect(page.locator("div.knowledge-status")).toContainText("请重新建立索引");
		await page.getByRole("button", { name: "建立／更新索引" }).click();
		await expect(page.locator("div.knowledge-status")).not.toContainText("请重新建立索引");
		fixture.faux.setResponses([fauxAssistantMessage('{"queries":["检索 vision 资料","资料 vision 检索"]}')]);
		await page.getByLabel("检索项目资料").fill("vision 资料");
		await page.getByRole("button", { name: "检索", exact: true }).click();
		await expect(page.locator(".knowledge-search-trace li")).toHaveCount(3);
		await expect(page.locator(".knowledge-search-trace")).toContainText("已扩展");
		await expect(page.locator(".knowledge-result")).toContainText("关键词");
		await page.getByRole("button", { name: "查看文档", exact: true }).click();
		await expect(page.getByRole("region", { name: "知识文档预览" })).toContainText("README.md");
		await expect(page.getByRole("region", { name: "知识文档预览" })).toContainText("视觉 vision baseline");
		await expect(page.getByText("browser-test-secret")).toHaveCount(0);
		await fixture.restart();
		await page.goto(fixture.address.launchUrl);
		await page.goto(`${fixture.address.origin}/projects/${(await fixture.application.services.projects.list())[0].id}/knowledge`);
		await expect(page.getByText("文件：1 · 片段：1")).toBeVisible();
	} finally {
		await fixture.close();
		await new Promise<void>((resolve, reject) => embedding.close((error) => error ? reject(error) : resolve()));
	}
});
